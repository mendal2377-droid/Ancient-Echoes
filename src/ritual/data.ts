// Rule-based matcher: score every poem by keyword hits in (text + chips),
// return the top 3 ids; pad with calm defaults when nothing matches.
export function matchPoems(text: string, tags: string[]): string[] {
  const hay = (text || '') + ' ' + (tags || []).join(' ')
  const scored = Object.keys(POEMS)
    .map(id => ({ id, score: (POEMS[id].kw ?? []).reduce((n, k) => n + (hay.indexOf(k) >= 0 ? 1 : 0), 0) }))
    .filter(s => s.score > 0)
    .sort((a, b) => b.score - a.score)
  if (!scored.length) return DEFAULTS.slice()
  const ids = scored.slice(0, 3).map(s => s.id)
  for (let i = 0; ids.length < 3 && i < DEFAULTS.length; i++) {
    if (ids.indexOf(DEFAULTS[i]) < 0) ids.push(DEFAULTS[i])
  }
  return ids
}

// ── THE VERIFICATION POINT ────────────────────────────────────────────────
// The oracle may name any poem in the tradition — it is not handed a menu, so
// its range is the whole of 中国古典诗歌 rather than whatever we managed to
// type in. What it names is resolved here, against this file. Anything that
// does not resolve is dropped and never reaches a reader; anything that does
// is rendered from the text *below*, never from the model's.
//
// So the model does the remembering and this file does the telling. The size
// of this table is therefore the app's real ceiling: a poem we cannot verify
// is a poem we cannot show, however well it answers.
const strip = (s: string) => (s || '').replace(/[《》「」『』（）()\s,，。、.]/g, '')
// 「·」 survives strip so a compound title can be split on it.
const parts = (title: string) => strip(title).split(/[·・]/).filter(Boolean)

export function resolvePoem(title: string, author: string): string | null {
  const a = strip(author)
  const want = parts(title)
  if (!want.length || !a) return null

  // Only ever consider this poet's work. A real title under the wrong name is
  // misattribution — the single most common way a model gets 唐诗 wrong, and
  // the one a reader would never catch.
  const byPoet = Object.keys(POEMS).filter(id => strip(POEMS[id].author) === a)

  // Score rather than filter. A plain filter treats 「遣悲怀三首·其一」 as
  // matching all three 遣悲怀 equally — they share that first part — and the
  // ambiguity rule below then discards the very poem that was named. Counting
  // matched parts separates the sibling that was asked for from the ones that
  // merely share its series title.
  const scored = byPoet.map(id => {
    const names = [POEMS[id].title, ...(POEMS[id].alias ?? [])]
    let score = 0
    // 水调歌头 / 水调歌头·明月几时有 — two naming habits, one poem. Whole parts
    // must match, so 相思令 does not collect 《相思》.
    for (const n of names) for (const h of parts(n)) if (want.includes(h)) score++
    // 词 are as often cited by opening line as by tune name, and an opening
    // line is far more specific than a shared series title.
    const first = strip(POEMS[id].lines[0] ?? '')
    if (first.length >= 4 && want.includes(first)) score += 2
    return { id, score }
  }).filter(s => s.score > 0)

  if (!scored.length) return null
  const best = Math.max(...scored.map(s => s.score))
  const top = scored.filter(s => s.score === best)

  // Ambiguity is still not resolution. 李商隐 wrote a shelf of 《无题》; where
  // nothing distinguishes them, we show none of them.
  return top.length === 1 ? top[0].id : null
}

// Every line in the corpus, punctuation removed, long enough to be a quotation
// rather than a coincidence. Five characters is the shortest classical line.
let verseCache: string[] | null = null
const verseLines = () => (verseCache ??= Object.keys(POEMS)
  .flatMap(id => POEMS[id].lines.map(strip))
  .filter(l => l.length >= 5))

/** Take the recited verse out of a 缘由 and return what remains.
 *
 *  A 缘由 is prose about the person, and quoted verse is the one place
 *  model-written poetry could reach the page unchecked — so it cannot stay.
 *  But dropping the whole sentence costs too much: the model typically quotes
 *  one line and then says something worth keeping, and a poem imported without
 *  a gloss has nothing to fall back on, leaving the card blank. So this cuts
 *  the offending clause and keeps the rest, if the rest still says something. */
export function stripVerse(text: string): string {
  const lines = verseLines()
  // clause + its trailing punctuation; no lookbehind, which older Safari
  // cannot even parse, and this module is bundled for the browser too.
  const segs = text.match(/[^，。；、！？]+[，。；、！？]?/g) ?? []
  const kept = segs
    .filter(seg => { const s = strip(seg); return !lines.some(l => s.includes(l)) })
    .join('')
    .replace(/^[，。；、！？\s]+/, '')
    .trim()
  return strip(kept).length >= 6 ? kept : ''
}

